export const LANG_NAMES = { en: 'EN', zh: '简', tw: '繁' }
export const lang = ref(localStorage.getItem('ec.lang') || 'en')

export function setLang(l) {
  lang.value = l
  localStorage.setItem('ec.lang', l)
}

export function t(key, vars) {
  const table = dict[lang.value] || dict.en
  let s = table[key] ?? dict.en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v)
  return s
}
